SCALE=2
def font(size,bold=False): return ImageFont.truetype(str(BOLD if bold else FONT),int(size*SCALE))
def wrapped(text,width,size):
    parts=[]
    probe=ImageFont.truetype(str(FONT),size)
    for paragraph in str(text).split('\n'):
        line=''
        for word in paragraph.split():
            candidate=(line+' '+word).strip()
            if line and probe.getlength(candidate)>width:
                parts.append(line);line=word
            else:line=candidate
        parts.append(line)
    return parts

class Canvas:
    def __init__(self,w,h):
        self.image=Image.new('RGB',(w*SCALE,h*SCALE),'white')
        self.draw=ImageDraw.Draw(self.image)
        self.svg=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}"><rect width="100%" height="100%" fill="white"/>']
    def rect(self,x,y,w,h,fill,stroke='#54718d',radius=10):
        self.svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" stroke="{stroke}" stroke-width="1.7"/>')
        self.draw.rounded_rectangle(tuple(int(v*SCALE) for v in [x,y,x+w,y+h]),radius=int(radius*SCALE),fill=fill,outline=stroke,width=3)
    def ellipse(self,x,y,w,h,fill,stroke='#54718d'):
        self.svg.append(f'<ellipse cx="{x+w/2}" cy="{y+h/2}" rx="{w/2}" ry="{h/2}" fill="{fill}" stroke="{stroke}" stroke-width="1.7"/>')
        self.draw.ellipse(tuple(int(v*SCALE) for v in [x,y,x+w,y+h]),fill=fill,outline=stroke,width=3)
    def diamond(self,x,y,w,h,fill):
        pts=[(x+w/2,y),(x+w,y+h/2),(x+w/2,y+h),(x,y+h/2)]
        self.svg.append('<polygon points="'+' '.join(f'{a},{b}' for a,b in pts)+f'" fill="{fill}" stroke="#54718d" stroke-width="1.7"/>')
        self.draw.polygon([(int(a*SCALE),int(b*SCALE)) for a,b in pts],fill=fill,outline='#54718d',width=3)
    def line(self,pts,stroke='#526f88',width=1.8,dashed=False,arrow=False):
        self.svg.append('<polyline points="'+' '.join(f'{x},{y}' for x,y in pts)+f'" fill="none" stroke="{stroke}" stroke-width="{width}"'+(' stroke-dasharray="7 5"' if dashed else '')+'/>')
        for p,q in zip(pts,pts[1:]):
            if dashed:
                dx,dy=q[0]-p[0],q[1]-p[1];length=math.hypot(dx,dy)
                for start in range(0,int(length),12):
                    end=min(start+7,length)
                    if length:self.draw.line([(int((p[0]+dx*t/length)*SCALE),int((p[1]+dy*t/length)*SCALE)) for t in [start,end]],fill=stroke,width=max(2,int(width*SCALE)))
            else:self.draw.line([(int(x*SCALE),int(y*SCALE)) for x,y in [p,q]],fill=stroke,width=max(2,int(width*SCALE)))
        if arrow and len(pts)>1:
            p,q=pts[-2],pts[-1];angle=math.atan2(q[1]-p[1],q[0]-p[0]);points=[q]
            points += [(q[0]-12*math.cos(angle-a),q[1]-12*math.sin(angle-a)) for a in [-.45,.45]]
            self.svg.append('<polygon points="'+' '.join(f'{x},{y}' for x,y in points)+f'" fill="{stroke}"/>')
            self.draw.polygon([(int(x*SCALE),int(y*SCALE)) for x,y in points],fill=stroke)
    def text(self,text,x,y,width,size=17,bold=False,color='#16334d',center=False,lineheight=None):
        lines=wrapped(text,width,size);lineheight=lineheight or size*1.35
        for i,line in enumerate(lines):
            xx=x+width/2 if center else x; yy=y+i*lineheight
            self.svg.append(f'<text x="{xx}" y="{yy+size}" font-family="Arial, sans-serif" font-size="{size}" font-weight="{700 if bold else 400}" fill="{color}"'+(' text-anchor="middle"' if center else '')+'>'+html.escape(line)+'</text>')
            self.draw.text((int(xx*SCALE),int(yy*SCALE)),line,font=font(size,bold),fill=color,anchor='mt' if center else 'lt')
        return len(lines)*lineheight
    def save(self,slug):
        for sub in ['01_Anh_SVG_de_chen_bao_cao','02_Anh_PNG_do_phan_giai_cao']:(OUT/sub).mkdir(exist_ok=True)
