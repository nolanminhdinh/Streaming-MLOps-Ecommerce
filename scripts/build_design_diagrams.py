def diagram(slug, title, kind, section, purpose, refs, width=1540, height=1100):
    d = dict(slug=slug, title=title, kind=kind, section=section, purpose=purpose,
             refs=refs, width=width, height=height, nodes=[], edges=[], notes=[])
    DIAGRAMS.append(d)
    return d

def node(d, key, name, x, y, w=270, h=90, kind='action', detail='', fill=BLUE, parent=None, columns=None):
    n = dict(key=key, name=name, x=x, y=y, w=w, h=h, kind=kind, detail=detail, fill=fill)
    if parent: n['parent'] = parent
    if columns: n['columns'] = columns
    d['nodes'].append(n)
    return key

def edge(d, a, b, label='', points=None, kind=None, dashed=False):
    d['edges'].append(dict(a=a, b=b, label=label, points=points, kind=kind, dashed=dashed))

def note(d, text, x, y, w, h=100):
    d['notes'].append(dict(text=text, x=x, y=y, w=w, h=h))

def col(name, typ='TEXT', pk=False, fk=False, nullable=False):
    return dict(name=name, type=typ, pk=pk, fk=fk, nullable=nullable)

